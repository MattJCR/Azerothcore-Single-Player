 (`Entry`,`Item`,`Reference`,`Chance`,`QuestRequired`,`LootMode`,`GroupId`,`MinCount`,`MaxCount`,`Comment`)
SELECT 700000+z.`zone_id`*3+3,z.`epic_item`,0,100,0,1,0,1,1,'SP03 tesoro por zona'
FROM `sp_treasure_zone` z WHERE z.`epic_slots`>0;

