-- SP06. Botín ponderado por zona y etapa de Individual Progression, para las
-- 57 zonas del catálogo de 01-tesoros.sql (generado por tramo de materiales;
-- el tramo de cada zona lo marcan sus `basic_item`/`rare_item`/`epic_item`).
-- No toca sp_treasure_zone, gameobject_template ni el punto/estado de cofres:
-- sólo gameobject_loot_template de entradas 700000+zona*3+calidad y conditions
-- de las etapas IP. Idempotente: borra el botín y las condiciones de todas las
-- zonas del catálogo antes de insertar (01-tesoros.sql ya sustituye el botín
-- original; este fichero se aplica después y lo reemplaza).
--
--  Básico: grupo de 4 materiales (tela/cuero/mineral/hierba) al 25% cada uno,
--          1-3 unidades de UN material por cofre.
--  Raro:   grupo gema (85%) + polvo de encantamiento (15%), más un bono
--          independiente (~5%) de una pieza azul BoE del tramo (no resta
--          probabilidad al material).
--  Épico:  la gema épica de 01-tesoros.sql no se toca aquí (se recrea abajo
--          igual); bono de equipo (~4%) y abalorio (0,1-0,4%). Terrallende exige
--          la misión 66008 y Rasganorte la 66013 (CONDITION_QUESTREWARDED,
--          fuente 4 GAMEOBJECT_LOOT_TEMPLATE); Vanilla alta no lleva condición.

DELETE `l` FROM `gameobject_loot_template` `l`
JOIN `sp_treasure_zone` `z` ON `l`.`Entry` IN
 (700000+`z`.`zone_id`*3+1, 700000+`z`.`zone_id`*3+2, 700000+`z`.`zone_id`*3+3);

DELETE `c` FROM `conditions` `c`
JOIN `sp_treasure_zone` `z` ON `c`.`SourceGroup` IN
 (700000+`z`.`zone_id`*3+1, 700000+`z`.`zone_id`*3+2, 700000+`z`.`zone_id`*3+3)
WHERE `c`.`SourceTypeOrReferenceId`=4;

-- Materiales garantizados originales (gema épica; el raro y el básico pasan a grupo).
